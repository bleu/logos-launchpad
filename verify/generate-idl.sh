#!/usr/bin/env bash
set -euo pipefail

if [ "${1:-}" = --actor ]; then
  [ "$#" = 1 ] || { echo 'usage: generate-idl.sh --actor' >&2; exit 1; }
  root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
  cd "$root"
  source verify/actor-tools.env
  mkdir -p packages/lez-compat/idl
  generated="$(mktemp)"
  trap 'rm -f "$generated"' EXIT
  cargo +"$ACTOR_RUST_VERSION" run --quiet --manifest-path packages/lez-compat/Cargo.toml -p lez-compat-tools --locked -- idl > "$generated"
  mv "$generated" packages/lez-compat/idl/compat.json
  exit 0
fi

# The default LEZ template has hand-written dispatch.  These declarations are
# its SPEL-facing ABI, generated by the project-pinned `spel` binary.
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root"
mkdir -p idl

for program in curve factory lbp private_buy; do
  temp=$(mktemp)
  lgs spel -- generate-idl "idl-src/${program}.rs" > "$temp"
  mv "$temp" "idl/${program}.json"
done
